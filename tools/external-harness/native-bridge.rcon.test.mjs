import assert from 'node:assert/strict'
import net from 'node:net'
import test from 'node:test'

import { Rcon } from '../../deploy/pterodactyl/runtime-v8/common.mjs'
import { NativeBridge } from './native-bridge.mjs'

// Real loopback TCP + production Source-RCON transport. The game response is
// scripted, not a Factorio engine result. Native semantics need the live lane.
function packet(id, type, text) {
  const payload = Buffer.from(text)
  const result = Buffer.alloc(payload.length + 14)
  result.writeInt32LE(payload.length + 10, 0)
  result.writeInt32LE(id, 4)
  result.writeInt32LE(type, 8)
  payload.copy(result, 12)
  return result
}

test('external native lifecycle traverses actual RCON TCP without a model/provider', async () => {
  const session = 'external-5fc5be97-0b8c-4c15-8da6-4c38bd74c590'
  const commands = []
  let admission
  let completed = false
  const status = () => ({
    task_state: admission && !completed ? 'waiting' : 'idle', queue_length: 0,
    batch_generation: 1, actor: { position: { x: 0, y: 0 } },
    ...(admission && !completed ? { active_batch: { batch_id: 1, batch_generation: 1, batch_ref: 'batch-g1-1', task_count: 1 } } : {}),
    admission_journal: admission ? [{ ...admission, state: completed ? 'completed' : 'admitted' }] : {},
    receipt_journal: completed ? [{ batch_id: 1, batch_generation: 1, batch_ref: 'batch-g1-1', state: 'completed', task_count: 1, task_types: ['waiting'], tick: 80 }] : {},
  })
  const respond = command => {
    commands.push(command)
    if (command.includes('{guard=remote.call')) return JSON.stringify({
      guard: { revision: 'sgluna-deploy-v8-npc-staging', session, mode: 'npc', actor_kind: 'standalone_character', actor_id: 10, epoch: 1, allowed: true, surface_index: 1 },
      status: status(), journal: { records: status().admission_journal, high_water: admission ? 1 : 0 }, tick: completed ? 80 : 10, speed: 1,
    })
    if (command.includes('local refusal=')) {
      // Recover the exact envelope generated by the reused v2 renderer. The
      // fixture does not execute Lua or independently manufacture correlation.
      const encoded = command.match(/helpers\.json_to_table\(("(?:[^"\\]|\\.)*")\)/)[1]
      const identity = JSON.parse(JSON.parse(encoded))
      admission = { ...identity, state: 'admitted', generation: 1, tick: 10, ok: true,
        slots: [{ index: 1, ok: true, operation: 'wait', queued_tasks: 1, batch_refs: [{ batch_id: 1, batch_generation: 1, batch_ref: 'batch-g1-1' }] }] }
      return `${command.match(/SGLUNA_RESULT_[a-f0-9]{24}:/)[0]}${JSON.stringify({ ok: true, result: [[true, 'queued']], admission })}`
    }
    return '{"ok":true}'
  }
  const sockets = new Set()
  const server = net.createServer(socket => {
    sockets.add(socket)
    socket.on('close', () => sockets.delete(socket))
    let buffer = Buffer.alloc(0)
    socket.on('data', chunk => {
      buffer = Buffer.concat([buffer, chunk])
      while (buffer.length >= 4) {
        const length = buffer.readInt32LE(0)
        if (buffer.length < length + 4) return
        const frame = buffer.subarray(4, length + 4)
        buffer = buffer.subarray(length + 4)
        const id = frame.readInt32LE(0)
        const type = frame.readInt32LE(4)
        const input = frame.subarray(8, -2).toString()
        if (type === 3) socket.write(packet(input === 'fixture-password' ? id : -1, 2, ''))
        else socket.write(packet(id, 0, respond(input)))
      }
    })
  })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  const rcon = new Rcon(server.address().port, 'fixture-password', 2000)
  try {
    await rcon.connect()
    const bridge = new NativeBridge({ rcon, session })
    const prepared = await bridge.prepare({ name: 'wait', args: { ticks: 60 } }, 'tcp/op_1')
    await bridge.submit(prepared)
    assert.equal((await bridge.receipt(prepared.pending)).state, 'running')
    completed = true
    const receipt = await bridge.receipt(prepared.pending)
    assert.equal(receipt.state, 'completed')
    assert.equal(receipt.goal_verified, false)
    assert.equal(receipt.evidence.receipts[0].batch_ref, 'batch-g1-1')
    assert.equal(commands.filter(command => command.includes('local refusal=')).length, 1)
  }
  finally {
    rcon.close()
    for (const socket of sockets) socket.destroy()
    await new Promise(resolve => server.close(resolve))
  }
})
